-- Authentication and collaboration.
--
-- * users: accounts. password_hash is NULL for someone who was added to a
--   workspace by email but has not registered yet ("pending"); registering
--   with that email claims the account.
-- * workspaces / workspace_members: every task belongs to exactly one
--   workspace, and only its members can see or change it.
-- * The old global "members" list becomes users. Existing tasks move to a
--   "Team board" workspace owned by those (pending) users, so no data is lost.

CREATE TABLE users (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email         VARCHAR(120) NOT NULL,
    display_name  VARCHAR(80)  NOT NULL,
    password_hash VARCHAR(255),
    created_at    TIMESTAMP(6) WITH TIME ZONE NOT NULL DEFAULT now(),
    CONSTRAINT uk_users_email UNIQUE (email),
    CONSTRAINT ck_users_email_lowercase CHECK (email = lower(email)),
    CONSTRAINT ck_users_email_format CHECK (email ~ '^[^@[:space:]]+@[^@[:space:]]+$'),
    CONSTRAINT ck_users_display_name_not_blank CHECK (btrim(display_name) <> '')
);

COMMENT ON TABLE users IS 'Accounts. Emails are stored lower-case, so the unique constraint is case-insensitive.';
COMMENT ON COLUMN users.password_hash IS 'DelegatingPasswordEncoder hash ({bcrypt}...). NULL = invited, not registered yet; cannot sign in.';

CREATE TABLE workspaces (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       VARCHAR(80) NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL DEFAULT now(),
    CONSTRAINT ck_workspaces_name_not_blank CHECK (btrim(name) <> '')
);

COMMENT ON TABLE workspaces IS 'A shared board. Tasks and memberships are deleted with it.';

CREATE TABLE workspace_members (
    workspace_id BIGINT      NOT NULL,
    user_id      BIGINT      NOT NULL,
    role         VARCHAR(20) NOT NULL,
    joined_at    TIMESTAMP(6) WITH TIME ZONE NOT NULL DEFAULT now(),
    CONSTRAINT pk_workspace_members PRIMARY KEY (workspace_id, user_id),
    CONSTRAINT fk_workspace_members_workspace FOREIGN KEY (workspace_id) REFERENCES workspaces (id) ON DELETE CASCADE,
    CONSTRAINT fk_workspace_members_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT ck_workspace_members_role CHECK (role IN ('OWNER', 'MEMBER'))
);

-- "My workspaces" looks memberships up by user; the primary key covers lookups by workspace.
CREATE INDEX ix_workspace_members_user ON workspace_members (user_id);

COMMENT ON TABLE workspace_members IS 'Who can access a workspace. OWNER manages members and the workspace; MEMBER works on tasks.';

-- Pending accounts for the former team members.
INSERT INTO users (email, display_name)
SELECT email, name FROM members;

-- One workspace for the existing board, only if there is anything to keep.
INSERT INTO workspaces (name)
SELECT 'Team board'
WHERE EXISTS (SELECT 1 FROM tasks) OR EXISTS (SELECT 1 FROM members);

INSERT INTO workspace_members (workspace_id, user_id, role)
SELECT w.id, u.id, 'OWNER'
FROM workspaces w CROSS JOIN users u;

-- Tasks: owning workspace, and who created / last changed them.
ALTER TABLE tasks
    ADD COLUMN workspace_id BIGINT,
    ADD COLUMN created_by   BIGINT,
    ADD COLUMN updated_by   BIGINT;

UPDATE tasks SET workspace_id = (SELECT min(id) FROM workspaces);

-- Assignees now reference users: remap member ids by email.
ALTER TABLE tasks DROP CONSTRAINT fk_tasks_assignee;
UPDATE tasks t
   SET assignee_id = u.id
  FROM members m
  JOIN users u ON u.email = m.email
 WHERE t.assignee_id = m.id;

ALTER TABLE tasks
    ALTER COLUMN workspace_id SET NOT NULL,
    ADD CONSTRAINT fk_tasks_workspace
        FOREIGN KEY (workspace_id) REFERENCES workspaces (id) ON DELETE CASCADE,
    -- The assignee must be a member of the task's workspace. Removing someone
    -- from the workspace unassigns their tasks there (and only there).
    ADD CONSTRAINT fk_tasks_assignee_membership
        FOREIGN KEY (workspace_id, assignee_id)
        REFERENCES workspace_members (workspace_id, user_id)
        ON DELETE SET NULL (assignee_id),
    -- Users are never deleted by the application; SET NULL keeps tasks if one is removed manually.
    ADD CONSTRAINT fk_tasks_created_by FOREIGN KEY (created_by) REFERENCES users (id) ON DELETE SET NULL,
    ADD CONSTRAINT fk_tasks_updated_by FOREIGN KEY (updated_by) REFERENCES users (id) ON DELETE SET NULL;

COMMENT ON COLUMN tasks.workspace_id IS 'Owning workspace; every read and write is scoped by it.';
COMMENT ON COLUMN tasks.assignee_id IS 'Assigned user; must be a member of the workspace. NULL when unassigned.';
COMMENT ON COLUMN tasks.created_by IS 'User who created the task; may delete it alongside workspace owners.';
COMMENT ON COLUMN tasks.updated_by IS 'User who made the last change.';

-- Board pages are now always read within one workspace: lead with workspace_id.
DROP INDEX ix_tasks_status_created;
DROP INDEX ix_tasks_status_due;
DROP INDEX ix_tasks_assignee;
CREATE INDEX ix_tasks_board_created ON tasks (workspace_id, status, created_at DESC, id DESC);
CREATE INDEX ix_tasks_board_due ON tasks (workspace_id, status, due_date ASC NULLS LAST, id DESC);
-- Assignee filter, and the membership foreign key's ON DELETE action.
CREATE INDEX ix_tasks_assignee ON tasks (workspace_id, assignee_id);

DROP TABLE members;

-- Single-use password reset links. Only a SHA-256 hash of the token is stored,
-- so a database leak cannot be turned into account takeovers.
CREATE TABLE password_reset_tokens (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT   NOT NULL,
    token_hash CHAR(64) NOT NULL,
    expires_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    used_at    TIMESTAMP(6) WITH TIME ZONE,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL DEFAULT now(),
    CONSTRAINT uk_password_reset_tokens_hash UNIQUE (token_hash),
    CONSTRAINT fk_password_reset_tokens_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT ck_password_reset_tokens_expiry CHECK (expires_at > created_at)
);

CREATE INDEX ix_password_reset_tokens_user ON password_reset_tokens (user_id);
